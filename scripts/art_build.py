"""Turn the 3D character renders (white background) into transparent PNGs for the app and
regenerate src/zk/art.ts.  Usage: python3 scripts/art_build.py voice-less folder of NAME_white.jpeg files
   python3 scripts/art_build.py /path/to/folder   (files named zoomi_white.jpeg, roarbow_white.jpeg, ...)"""
import glob, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
from art_cutout import white_to_alpha

src = sys.argv[1] if len(sys.argv) > 1 else None
out = os.path.join(ROOT, 'assets', 'chars')
os.makedirs(out, exist_ok=True)
if src:
    for f in sorted(glob.glob(os.path.join(src, '*_white.jpeg'))):
        name = os.path.basename(f).replace('_white.jpeg', '')
        # White characters (penguin, bird) on a white backdrop need a strict match, or their white
        # feathers get cut away; their enclosed pockets are not treated as background either.
        white_chars = {'puddle': dict(tol=5, pocket=10 ** 9), 'rio': dict(tol=5, pocket=10 ** 9)}
        white_to_alpha(f, os.path.join(out, name + '.png'), size=560, **white_chars.get(name, {}))
        print('cut', name)
names = sorted(os.path.splitext(os.path.basename(p))[0] for p in glob.glob(os.path.join(out, '*.png')))
lines = ['// Generated by scripts/art_build.py — do not edit by hand.', '/* eslint-disable */',
         '/** 3D character renders (transparent PNG). A character without one falls back to its drawing. */',
         'export const ART: Record<string, number> = {']
lines += [f"  {n}: require('../../assets/chars/{n}.png')," for n in names]
lines += ['};', '']
open(os.path.join(ROOT, 'src', 'zk', 'art.ts'), 'w').write('\n'.join(lines))
print('art.ts:', names)
